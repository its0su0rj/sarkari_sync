#!/usr/bin/env python3
"""
Writes the public data for the static site:
    site/jobs.json   open jobs (facts and links only, no copied article text)
    site/config.js   Telegram bot username from $TELEGRAM_BOT_USERNAME

    python build_site.py [--db sarkari.db] [--out site]
"""
import argparse
import json
import os
import sqlite3
from datetime import date, timedelta

from eligibility import load_jobs

KEEP = ("link", "title", "categories", "dates", "date_notes", "age", "fees", "total_posts",
        "qualification_text", "links")


def build(db_path: str, out_dir: str) -> int:
    jobs = load_jobs(db_path)
    # Keep jobs still open (with 1 day of slack for time zones) or with no fixed last date.
    cutoff = (date.today() - timedelta(days=1)).isoformat()
    public = []
    for j in jobs:
        last = (j.get("dates") or {}).get("last_date")
        if last and last < cutoff:
            continue
        public.append({k: j.get(k) for k in KEEP})
    public.sort(key=lambda j: ((j.get("dates") or {}).get("last_date") or "9999", j["title"]))
    db = sqlite3.connect(db_path)
    row = db.execute("SELECT value FROM meta WHERE key='last_success'").fetchone()
    db.close()
    os.makedirs(out_dir, exist_ok=True)
    with open(os.path.join(out_dir, "jobs.json"), "w", encoding="utf-8") as fh:
        json.dump({"last_sync": row[0] if row else None, "jobs": public}, fh, ensure_ascii=False, separators=(",", ":"))
    bot = os.environ.get("TELEGRAM_BOT_USERNAME", "").lstrip("@").strip()
    with open(os.path.join(out_dir, "config.js"), "w", encoding="utf-8") as fh:
        fh.write("// Generated by build_site.py\n")
        fh.write(f"window.EXAMMATCH_CONFIG = {json.dumps({'telegramBot': bot})};\n")
    print(f"site: {len(public)} open jobs -> {out_dir}/jobs.json; telegram bot: {bot or '(none)'}")
    return len(public)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--db", default="sarkari.db")
    ap.add_argument("--out", default="site")
    a = ap.parse_args()
    build(a.db, a.out)
